const c10 = after(V, s, 'a2-a3'); console.log(chk(c10))
hr('C11 promotion check: W pawn e7-e8=q? black king h8: e8 queen checks h8 along rank (f8,g8 empty)')
s = stateOf(V, [[{ a1: '0:k', e7: '0:p', h8: '1:k' }, 1]], 0, C([0, 0]))
console.log(codes(V, s).filter(c => c.startsWith('e7')))
const c11 = after(V, s, 'e7-e8=q'); console.log(chk(c11)); const c11n = after(V, s, 'e7-e8=n'); console.log('knight promo', chk(c11n))
hr('C12 black counter: black gives check')
s = stateOf(V, [[{ e1: '0:k', a8: '1:r', h8: '1:k' }, 1]], 1, C([0, 0]))
